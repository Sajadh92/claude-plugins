#!/usr/bin/env python3
"""Abo Fles topic lookup — the skill's Step 2 in one Bash call.

  topic.py find "<the ask, 3-8 words>" [--limit 3] [--cwd <project>]   top matches: tier, cells, reviewers, workflow, 💡 suggestions
  topic.py show <#|name>                                                one topic in full (signals, header template)
  topic.py domains                                                      the domain table
  topic.py list <CODE>                                                  the topics of one domain

Reads hooks/workflow.json (generated by scripts/gen_matrix.py). Project overrides (`Topic: Name = T#`,
`Topic / Side = model·effort`, `Topic / Side cap = N`) from the `## abofles overrides` block are applied and marked.
"""
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "hooks"))
from abofles_hook import workflow_table, topic_matches, topic_cells, override_value, REVIEW_SIDES, tier_name  # noqa: E402

SIDES = ("Read", "Analyse", "Plan", "Work", "Verify")
STACK_FILES = {
    "dotnet": (".csproj", ".sln", ".fsproj", "global.json", "Directory.Build.props"),
    "node": ("package.json",),
    "python": ("pyproject.toml", "requirements.txt", "setup.py", "Pipfile"),
    "java": ("pom.xml", "build.gradle", "build.gradle.kts"),
    "go": ("go.mod",),
    "rust": ("Cargo.toml",),
    "php": ("composer.json",),
    "ruby": ("Gemfile",),
    "swift": ("Package.swift", ".xcodeproj"),
    "flutter": ("pubspec.yaml",),
}
SKIP_DIRS = {"node_modules", ".git", "bin", "obj", "vendor", "dist", "build", ".venv", "venv", "__pycache__", ".worktrees", "target", "Pods"}


def stacks_of(cwd, depth=2):
    """Stacks whose manifest files sit in the working tree (depth 2, big folders skipped)."""
    found = set()
    root = Path(cwd or os.getcwd())
    try:
        for dirpath, dirnames, filenames in os.walk(root):
            rel_depth = len(Path(dirpath).relative_to(root).parts)
            dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS and not d.startswith(".")] if rel_depth < depth else []
            for f in filenames + dirnames:
                for stack, marks in STACK_FILES.items():
                    if any(f == m or f.endswith(m) for m in marks):
                        found.add(stack)
    except Exception:
        pass
    return found


def tier_of(name, info, cwd):
    v = override_value(cwd, f"Topic: {name}") if cwd else None
    m = re.match(r"\s*T?([1-4])\s*$", v or "")
    return (int(m.group(1)), True) if m else (info.get("tier") or 2, False)


def cells_line(name, info, tier, wf, cwd):
    parts, ov = [], False
    cells = topic_cells(info, tier, wf)
    for side in SIDES:
        cell, cap, src = cells[side]
        pc = override_value(cwd, f"{name} / {side}") if cwd else None
        pcap = override_value(cwd, f"{name} / {side} cap") if cwd else None
        if pc:
            cell, ov = pc.strip(), True
        if pcap and pcap.strip().isdigit():
            cap, ov = int(pcap), True
        parts.append(f"{side} {cell}/{cap}" + ("*" if src == "topic" and not pc else ""))
    return " · ".join(parts) + (" · Project Override" if ov else "")


def reviewers_line(info, cwd, wf, name):
    g = info.get("group")
    gname = ((wf.get("groups") or {}).get(g) or {}).get("name", "")
    out = []
    for t in ("3", "4"):
        names = None
        for key in (name, gname, g):
            v = override_value(cwd, f"Reviewers: {key}") if cwd and key else None
            if v is not None:
                names = [x for x in re.split(r"[,\s]+", v.strip().lower()) if x and x != "none" and x in REVIEW_SIDES]
                break
        if names is None:
            names = (info.get("reviewers") or {}).get(t, [])
        out.append(f"T{t} " + (", ".join(REVIEW_SIDES.get(n, n) for n in names) or "—"))
    return "reviewers " + " · ".join(out)


def workflow_line(tier, wf):
    steps = (wf.get("change") or {}).get(str(tier)) or []
    return "change → " + " → ".join(steps)


def topic_block(rank, name, info, wf, cwd):
    tier, tov = tier_of(name, info, cwd)
    g = info.get("group")
    gname = ((wf.get("groups") or {}).get(g) or {}).get("name", "")
    head = f"{rank}. #{info.get('n')} {name} · {g} {gname} / {info.get('area')} · {tier_name(tier)} (T{tier}){' · Project Override' if tov else ''} · {reviewers_line(info, cwd, wf, name)}"
    return head + "\n   " + cells_line(name, info, tier, wf, cwd) + " · " + workflow_line(tier, wf)


def suggestions_for(matches, query, wf, cwd):
    sugs = wf.get("suggestions") or {}
    if not sugs:
        return []
    stacks = stacks_of(cwd)
    q = (query or "").lower()
    out, seen = [], set()
    for _, name, info in matches:
        for key in info.get("suggest") or []:
            sg = sugs.get(key)
            if not sg or key in seen:
                continue
            words = [w.strip() for w in (sg.get("stack_words") or "").split(",") if w.strip()]
            if sg.get("stack") in stacks or any(w in q for w in words):
                seen.add(key)
                out.append(f"💡 suggest · {sg['name']} (stack {sg.get('stack')}) for {name}: {sg['text']}")
    return out


def main(argv):
    wf = workflow_table()
    if not wf.get("topics"):
        print("abofles: hooks/workflow.json missing — run python3 scripts/gen_matrix.py")
        return 1
    args = list(argv)
    cwd = os.getcwd()
    if "--cwd" in args:
        i = args.index("--cwd")
        cwd = args[i + 1]
        del args[i:i + 2]
    limit = 3
    if "--limit" in args:
        i = args.index("--limit")
        limit = int(args[i + 1])
        del args[i:i + 2]
    cmd = args[0] if args else "find"
    rest = " ".join(args[1:]).strip()
    topics = wf["topics"]
    if cmd == "domains":
        print("| Code | Domain | Topics | Reviewers T3 → T4 | Covers |")
        for code, g in (wf.get("groups") or {}).items():
            count = sum(1 for t in topics.values() if t.get("group") == code)
            r = g.get("reviewers") or {}
            print(f"| {code} | {g.get('name')} | {count} | {', '.join(REVIEW_SIDES.get(x, x) for x in r.get('3', [])) or '—'} → {', '.join(REVIEW_SIDES.get(x, x) for x in r.get('4', [])) or '—'} | {g.get('blurb', '')} |")
        return 0
    if cmd == "list":
        code = rest.upper()
        rows = sorted(((i.get("n"), n, i) for n, i in topics.items() if i.get("group") == code), key=lambda x: x[0] or 0)
        if not rows:
            print(f"no domain {code!r} — codes: " + ", ".join(wf.get("groups") or {}))
            return 1
        area = None
        for n, name, info in rows:
            if info.get("area") != area:
                area = info.get("area")
                print(f"{area}:")
            print(f"  #{n} {name} · T{info.get('tier')}")
        return 0
    if cmd == "show":
        key = rest
        info = topics.get(key)
        name = key
        if not info and key.lstrip("#").isdigit():
            n = int(key.lstrip("#"))
            name, info = next(((nm, i) for nm, i in topics.items() if i.get("n") == n), (None, None))
        if not info:
            near = topic_matches(key, wf, 1)
            if not near:
                print(f"no topic {key!r}")
                return 1
            _, name, info = near[0]
        print(topic_block(1, name, info, wf, cwd))
        print(f"   signals: {info.get('signals', '')}")
        print(f"   header: abofles: {name} / <Side> · T{tier_of(name, info, cwd)[0]}")
        for line in suggestions_for([(0, name, info)], "", wf, cwd):
            print(line)
        return 0
    # find
    query = rest if cmd == "find" else " ".join(args)
    if not query:
        print(__doc__.strip())
        return 2
    matches = topic_matches(query, wf, limit)
    if not matches:
        print(f'🔎 topic lookup · "{query}" · no match — use the fast tier test and the closest domain (`topic.py domains`); tell the user the topic is new.')
        return 0
    stacks = sorted(stacks_of(cwd))
    print(f'🔎 topic lookup · "{query}" · {len(matches)} match{"es" if len(matches) > 1 else ""}' + (f" · stack {', '.join(stacks)}" if stacks else ""))
    for rank, (score, name, info) in enumerate(matches, 1):
        print(topic_block(rank, name, info, wf, cwd))
    for line in suggestions_for(matches, query, wf, cwd):
        print(line)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
